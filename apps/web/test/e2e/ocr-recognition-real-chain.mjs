// Real React/Axum/owned PostgreSQL. Only the model supplier is a loopback mock.
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const directory=process.env.OCR_AUDIT_PROOF_OUTPUT;assert.ok(directory);
const fixture=JSON.parse(await readFile(path.join(directory,'recognition-fixture.json'),'utf8'));
const {origin,workRef,domain}=fixture;
const endpoint=new URL(origin);assert.equal(endpoint.hostname,'127.0.0.1');assert.notEqual(endpoint.port,'3000');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1100}});
await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
const page=await context.newPage();page.setDefaultTimeout(30000);
const errors=[];const writes=[];page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(request.method()==='POST')writes.push(new URL(request.url()).pathname);});
const statePath='/api/local/work-resources/'+encodeURIComponent(workRef)+'/ocr-recognition';
const read=async()=>{const response=await page.request.get(origin+statePath);assert.equal(response.status(),200,await response.text());return response.json();};
try{
 await page.goto(origin+'/settings/models?view=advanced&area=work&task=ocr_recognition');
 await page.getByRole('heading',{name:'OCR 模型',exact:true}).waitFor();
 await page.getByRole('combobox',{name:'选择 OCR 模型',exact:true}).waitFor();
 const settings=await page.request.get(origin+'/api/local/ai-settings');const before=await settings.json();
 const controls=before.controls.map(row=>({scope:row.scope,enabled:row.enabled}));
 await page.screenshot({path:path.join(directory,'recognition-settings.png'),fullPage:true});
 const saved=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/local/ai-settings/task-configs'&&r.request().method()==='POST');
 await page.getByRole('button',{name:'保存配置',exact:true}).click();const savedResponse=await saved;assert.equal(savedResponse.status(),200,await savedResponse.text());
 const after=await (await page.request.get(origin+'/api/local/ai-settings')).json();
 assert.deepEqual(after.controls.map(row=>({scope:row.scope,enabled:row.enabled})),controls);
 assert.equal((await read()).runRef,null,'saving settings sends no image and creates no run');
 await page.goto(origin+'/corpus/evidence?domain='+encodeURIComponent(domain)+'&work='+encodeURIComponent(workRef)+'&tab=overview&panel=focus');
 const action=page.locator('[data-ocr-action]');await action.waitFor();await page.getByRole('button',{name:'OCR 识别',exact:true}).waitFor();
 await page.screenshot({path:path.join(directory,'recognition-ready.png'),fullPage:true});
 await action.click();await page.getByRole('group',{name:'确认本篇图片识别范围',exact:true}).waitFor();
 assert.equal((await read()).runRef,null,'scope confirmation is read-only');
 await page.getByRole('button',{name:'确认并开始识别',exact:true}).click();
 await page.getByRole('button',{name:'识别中 33%',exact:true}).waitFor();
 assert.equal((await read()).completedImages,1,'33% comes from first committed image');
 assert.equal(await action.getAttribute('style'),'--ocr-progress: 33%;');
 assert.equal(await page.getByRole('progressbar',{name:'图片文字识别进度'}).getAttribute('aria-valuetext'),'33%');
 assert.doesNotMatch(await action.innerText(),/\d+\s*\/\s*\d+/);
 await page.screenshot({path:path.join(directory,'recognition-progress-33.png'),fullPage:true});
 const release=await page.request.post(origin+'/__ocr-proof/release');assert.equal(release.status(),200);
 await page.getByRole('button',{name:'查看识别结果',exact:true}).waitFor();
 const final=await read();assert.equal(final.state,'succeeded');assert.equal(final.completedImages,final.totalImages);
 assert.equal(final.totalImages,3);assert.ok(final.coverTitle,'first image yields a real literal candidate');
 const result=page.getByRole('region',{name:'图片文字识别结果',exact:true});await result.waitFor();
 await result.getByText(final.coverTitle,{exact:true}).waitFor();
 assert.ok(final.images.every(image=>image.originalUrl&&image.rawJson&&image.usage?.measuredTokens!==null));
 await page.getByRole('button',{name:'查看识别结果',exact:true}).click();
 const resultHeading=await result.getByRole('heading',{name:'图片文字',exact:true}).boundingBox();
 const inspectorTab=await page.getByRole('tab',{name:'作品',exact:true}).boundingBox();
 assert.ok(resultHeading&&inspectorTab&&resultHeading.y>=inspectorTab.y+inspectorTab.height,'view results lands below the sticky inspector header');
 await page.screenshot({path:path.join(directory,'recognition-result.png'),fullPage:true});
 await result.getByRole('button',{name:'逐图对照',exact:true}).click();
 await result.locator('details').filter({has:page.getByText('原始识别与运行回执',{exact:true})}).locator(':scope > summary').click();
 const firstRaw=result.locator('details').filter({has:page.getByText('第 1 图 · 原始 JSON 与用量',{exact:true})}).last();
 await firstRaw.locator(':scope > summary').click();
 assert.equal(await page.getByLabel('第 1 图原始 JSON',{exact:true}).textContent(),final.images[0].rawJson);
 await page.getByLabel('第 1 图原始 JSON',{exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(directory,'recognition-raw-json.png'),fullPage:true});
 await result.getByRole('button',{name:'核对原图',exact:true}).first().click();await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'关闭查看器',exact:true}).click();
 await page.reload();await page.getByRole('button',{name:'查看识别结果',exact:true}).waitFor();
 assert.equal((await read()).runRef,final.runRef,'refresh only reads the existing run');
 await page.setViewportSize({width:980,height:1100});await page.screenshot({path:path.join(directory,'recognition-narrow.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 assert.equal(writes.filter(p=>p===statePath).length,1,'one explicit browser start command');
 await writeFile(path.join(directory,'recognition-browser-result.json'),JSON.stringify({result:'PASS',scope:'actual React/API/owned PG; supplier mock; no real calls',writes,errors,runRef:final.runRef,observedPercentage:33,finalPercentage:100,steps:['model configuration saved without dispatch or switch changes','current-work scope confirmation','committed percentage in button','title/body/raw JSON and original viewer','refresh retains persisted result']},null,2));
 console.log('Manual OCR browser: model → scope → persisted 33% → saved results/raw/source → refresh PASS');
}catch(error){await writeFile(path.join(directory,'recognition-browser-failure.html'),await page.content());await page.screenshot({path:path.join(directory,'recognition-browser-failure.png'),fullPage:true});throw error;}
finally{await browser.close();}
