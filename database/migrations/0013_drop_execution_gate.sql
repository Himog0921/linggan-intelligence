-- COLLECTION-001 · 删除真实执行闸门
--
-- Mog 于 2026-08-28 从第一性原理推翻了它：闸门是一个必须由人反复「上弦」的开关，而
-- 目标系统必须无人值守地跑（10 个工位、1000 篇/天）。这样的开关只有两种下场——
-- 要么开一个长窗口然后忘掉，变成**看起来像控制的装饰**（比没有更危险）；要么每天去开
-- 几次，那监控这件事本身就不成立。
--
-- 稳态真正在管事的是另外三样，它们的共同点是**默认允许、有界、自己复位**：
--   · 每日额度（200 篇/工位，按 Asia/Shanghai 自然日自动重置）
--   · 风险暂停（出事踩一脚，平时不存在）
--   · 采集授权到期（30 天，强制定期重新同意）
--
-- 再往下一层：闸门在稳态只能「一直开着、出事关掉」——那就**是**风险暂停，两个对象
-- 干一件事。它在自举期确有价值（系统一次没跑过、需要一个会自己过期的「去」），但那个
-- 价值有保质期，而现在保质期到了。
--
-- 删表而不是留着不用：留着的死控制会让下一个人以为系统有一道它其实没有的防线。

DROP TABLE collection_execution_gate;
