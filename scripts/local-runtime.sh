#!/usr/bin/env bash
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$project_root"

usage() {
  cat >&2 <<'EOF'
usage: ./scripts/local-runtime.sh {migrate|repair-password|bootstrap-ops-admin|serve} [--database database_name]

  migrate          apply the approved local Linggan migrations exactly once
  repair-password  explicitly align the local persistent database role with .env
  bootstrap-ops-admin
                   create exactly one invited first Ops administrator from controlled console input
serve            migrate, then start API, patrol, media and the controlled AI executor

The optional --database form is reserved for an exact, disposable runtime proof
database. It refuses every name except linggan_intelligence_runtime_proof_<hex>.
EOF
}

ensure_env() {
  local requested_port="${LINGGAN_LOCAL_PORT:-}"
  "$project_root/scripts/setup-local-env.sh" >/dev/null
  set -a
  # shellcheck disable=SC1091
  source "$project_root/.env"
  set +a
  if [[ -n "$requested_port" ]]; then
    export LINGGAN_LOCAL_PORT="$requested_port"
  fi
  if [[ -n "${LINGGAN_RUSTUP_BIN_DIR:-}" ]]; then
    [[ -x "$LINGGAN_RUSTUP_BIN_DIR/cargo" ]] \
      || { echo "LINGGAN_RUSTUP_BIN_DIR has no cargo executable" >&2; exit 1; }
    export PATH="$LINGGAN_RUSTUP_BIN_DIR:$PATH"
  fi

  if [[ "${POSTGRES_PASSWORD:-}" == replace-* || "${#POSTGRES_PASSWORD}" -lt 24 ]]; then
    echo "POSTGRES_PASSWORD must be a non-placeholder local secret with at least 24 characters" >&2
    exit 1
  fi

  if [[ "${POSTGRES_USER:-}" != "linggan_dev_admin" || -z "${POSTGRES_DB:-}" ]]; then
    echo "local environment must use linggan_dev_admin and POSTGRES_DB" >&2
    exit 1
  fi

  if [[ ! "${POSTGRES_PORT:-}" =~ ^[1-9][0-9]{0,4}$ ]] || (( POSTGRES_PORT > 65535 )); then
    echo "POSTGRES_PORT must be a valid local TCP port" >&2
    exit 1
  fi
}

database_name=""
if [[ "${1:-}" == "--database" ]]; then
  database_name="${2:-}"
  shift 2
  if [[ ! "$database_name" =~ ^linggan_intelligence_runtime_proof_[0-9a-f]+$ ]]; then
    echo "--database only accepts an exact disposable runtime proof database name" >&2
    exit 1
  fi
fi

if [[ $# -ne 1 ]]; then
  usage
  exit 1
fi
command_name="$1"

psql_in_container() {
  docker compose exec -T postgres psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$database_name" "$@"
}

local_database_url() {
  # POSTGRES_PASSWORD is generated as hex and POSTGRES_USER is fixed, so neither needs URL
  # escaping. This is intentionally derived from the exact Compose target; DATABASE_ADMIN_URL
  # is not an authority for the runtime target and must never redirect the API after migration.
  printf 'postgresql://%s:%s@127.0.0.1:%s/%s' \
    "$POSTGRES_USER" "$POSTGRES_PASSWORD" "$POSTGRES_PORT" "$database_name"
}

bind_runtime_database_target() {
  local derived_url
  derived_url="$(local_database_url)"
  if [[ -n "${LINGGAN_LOCAL_DATABASE_URL:-}" && "$LINGGAN_LOCAL_DATABASE_URL" != "$derived_url" ]]; then
    echo "LINGGAN_LOCAL_DATABASE_URL conflicts with the exact database verified by migration; refusing to start" >&2
    exit 1
  fi
  export LINGGAN_LOCAL_DATABASE_URL="$derived_url"
}

verify_runtime_port_binding() {
  local published_address
  published_address="$(docker compose port postgres 5432)"
  if [[ "$published_address" != "127.0.0.1:${POSTGRES_PORT}" ]]; then
    echo "the Compose PostgreSQL port does not match the local runtime target; refusing to continue" >&2
    exit 1
  fi
}

verify_application_database_credentials() {
  # The database container's loopback hba rule is trust-based. Verify through
  # a separate Compose client on the database network instead, so this proves
  # the password works for the application connection path. The current .env
  # secret travels only on stdin: it must never become a Docker CLI argument.
  if ! printf '%s\n' "$POSTGRES_PASSWORD" | docker compose run --rm --no-deps -T postgres \
    sh -ceu '
      IFS= read -r database_password
      case "$database_password" in
        ""|*[!0-9a-f]*)
          echo "POSTGRES_PASSWORD must be the hex local secret generated by setup-local-env.sh" >&2
          exit 1
          ;;
      esac
      PGPASSWORD="$database_password" exec psql -X -v ON_ERROR_STOP=1 -h postgres \
        -U linggan_dev_admin -d "$1" -c "SELECT 1;"
    ' sh "$database_name" >/dev/null; then
    echo "the local database role does not accept the current .env password; no data was changed" >&2
    echo "run ./scripts/local-runtime.sh repair-password to explicitly align this local-only role, then retry" >&2
    exit 1
  fi
}

verify_persistent_runtime_is_stopped_for_migration() {
  local label launchctl_result
  [[ "$database_name" == "$POSTGRES_DB" ]] || return 0
  if ! command -v launchctl >/dev/null 2>&1; then
    echo "cannot verify local runtime services are stopped; refusing persistent database migration" >&2
    exit 1
  fi
  for label in com.linggan-intelligence.local-runtime \
    com.linggan-intelligence.patrol-worker com.linggan-intelligence.media-worker com.linggan-intelligence.ai-executor; do
    if launchctl_result="$(launchctl print "gui/$(id -u)/$label" 2>&1)"; then
      echo "${label} must be stopped before persistent database migration; use scripts/runtime/install.sh --prepare-migration" >&2
      exit 1
    fi
    if [[ "$launchctl_result" != *"Could not find service \"$label\" "* ]]; then
      echo "cannot confirm $label is stopped; refusing persistent database migration" >&2
      echo "$launchctl_result" >&2
      exit 1
    fi
  done
  for process in linggan-api linggan-worker linggan-media-worker linggan-ai-worker; do
    if pgrep -x "$process" >/dev/null 2>&1; then
      echo "${process} is still running; refusing persistent database migration" >&2
      exit 1
    fi
  done
  local application_port="${LINGGAN_LOCAL_PORT:-3000}"
  if [[ ! "$application_port" =~ ^[1-9][0-9]{0,4}$ ]] || (( application_port > 65535 )); then
    echo "LINGGAN_LOCAL_PORT must be a valid non-zero TCP port" >&2
    exit 1
  fi
  if lsof -nP -iTCP:"$application_port" -sTCP:LISTEN >/dev/null 2>&1; then
    echo "port ${application_port} is still serving; refusing persistent database migration" >&2
    exit 1
  fi
}

prepare_historical_comment_schema() {
  # Historical deltas 0107–0178 require this scaffold. It is removed by 0179 and
  # must never be recreated on a current or already-upgraded database.
  local legacy_count
  legacy_count="$(psql_in_container -Atc "SELECT count(*) FROM information_schema.tables WHERE table_schema='public' AND table_name LIKE 'linggan_comment_study_%'")"
  if [[ "$legacy_count" == 0 ]]; then
    { printf 'BEGIN;\n'; cat "$project_root/database/bootstrap/comment-study-001.sql"; printf '\nCOMMIT;\n'; } | psql_in_container >/dev/null
  fi
}

repair_password() {
  "$project_root/scripts/dev-db.sh" up >/dev/null
  # The container may have been created with an older secret. Pass the value
  # just verified from this invocation's .env over stdin; never select the
  # container's startup environment as the repair authority or place it in a
  # Docker CLI argument.
  printf '%s\n' "$POSTGRES_PASSWORD" | docker compose exec -T postgres sh -ceu '
    IFS= read -r repair_password
    case "$repair_password" in
      ""|*[!0-9a-f]*)
        echo "POSTGRES_PASSWORD must be the hex local secret generated by setup-local-env.sh" >&2
        exit 1
        ;;
    esac
    printf "ALTER ROLE linggan_dev_admin PASSWORD '\''%s'\'';\\n" "$repair_password" \
      | psql -X -v ON_ERROR_STOP=1 -U linggan_dev_admin -d postgres >/dev/null
  '
  verify_application_database_credentials
  echo "local database role password aligned with the existing .env; persisted data was not reset or removed"
}

require_ops_first_admin_bootstrap_schema() {
  local expected_hash recorded_hash relation
  expected_hash="$(shasum -a 256 "$project_root/database/migrations/0153_ops_first_admin_bootstrap.sql" | awk '{print $1}')"
  recorded_hash="$(psql_in_container -At -c "SELECT migration_sha256 FROM linggan_local_schema_migration WHERE migration_id='0153_ops_first_admin_bootstrap'")"
  relation="$(psql_in_container -At -c "SELECT to_regclass('linggan_ops_first_admin_bootstrap')")"
  if [[ "$recorded_hash" != "$expected_hash" || "$relation" != "linggan_ops_first_admin_bootstrap" ]]; then
    echo "0153_ops_first_admin_bootstrap is not the verified current schema; run the explicit migrate workflow first" >&2
    exit 1
  fi
}

bootstrap_ops_admin() {
  local email display_name confirmation raw_token token_digest email_base64 display_name_base64
  confirmation="${LINGGAN_OPS_BOOTSTRAP_CONFIRM:-}"
  if [[ "$confirmation" != "CREATE_FIRST_OPS_ADMIN" ]]; then
    echo "set LINGGAN_OPS_BOOTSTRAP_CONFIRM=CREATE_FIRST_OPS_ADMIN to acknowledge this one-time action" >&2
    exit 1
  fi
  if ! IFS= read -r raw_token || ! IFS= read -r email || ! IFS= read -r display_name; then
    echo "provide bootstrap token, email and display name as exactly three stdin lines" >&2
    exit 1
  fi
  if [[ ! "$email" =~ ^[^[:space:]@]+@[^[:space:]@]+$ ]] || (( ${#email} > 320 )); then
    echo "bootstrap email must contain one nonblank local and domain part" >&2
    exit 1
  fi
  if [[ -z "${display_name//[[:space:]]/}" || ${#display_name} -gt 160 ]]; then
    echo "bootstrap display name must be 1 to 160 nonblank characters" >&2
    exit 1
  fi
  if [[ ! "$raw_token" =~ ^[0-9A-Fa-f]{64}$ ]]; then
    echo "bootstrap token must be exactly 64 hexadecimal characters" >&2
    exit 1
  fi
  token_digest="$(printf '%s' "$raw_token" | shasum -a 256 | awk '{print $1}')"
  email_base64="$(printf '%s' "$email" | base64 | tr -d '\n')"
  display_name_base64="$(printf '%s' "$display_name" | base64 | tr -d '\n')"
  unset raw_token email display_name

  verify_persistent_runtime_is_stopped_for_migration
  "$project_root/scripts/dev-db.sh" up >/dev/null
  verify_runtime_port_binding
  verify_application_database_credentials
  require_ops_first_admin_bootstrap_schema
  psql_in_container -q -v ON_ERROR_STOP=1 <<SQL
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('linggan_ops_first_admin_bootstrap'));
DO \$\$ BEGIN
    IF EXISTS (SELECT 1 FROM linggan_ops_first_admin_bootstrap)
       OR EXISTS (SELECT 1 FROM linggan_ops_member) THEN
        RAISE EXCEPTION 'first Ops administrator bootstrap is no longer available';
    END IF;
END \$\$;
CREATE TEMP TABLE first_admin_bootstrap_input (
    member_ref uuid NOT NULL,
    invite_ref uuid NOT NULL,
    email text NOT NULL,
    display_name text NOT NULL,
    token_digest bytea NOT NULL
) ON COMMIT DROP;
INSERT INTO first_admin_bootstrap_input
SELECT gen_random_uuid(),gen_random_uuid(),
       convert_from(decode('${email_base64}','base64'),'UTF8'),
       convert_from(decode('${display_name_base64}','base64'),'UTF8'),
       decode('${token_digest}','hex');
INSERT INTO linggan_ops_member (member_ref,email_normalized,display_name,role,state)
SELECT member_ref,lower(btrim(email)),btrim(display_name),'admin','invited'
FROM first_admin_bootstrap_input;
INSERT INTO linggan_ops_invite (invite_ref,member_ref,token_sha256,invited_by_member_ref,expires_at)
SELECT invite_ref,member_ref,token_digest,member_ref,scope_001_now() + make_interval(secs => 604800)
FROM first_admin_bootstrap_input;
INSERT INTO linggan_ops_first_admin_bootstrap
    (bootstrap_ref,member_ref,invite_ref,request_ref,control_channel)
SELECT gen_random_uuid(),member_ref,invite_ref,gen_random_uuid(),'local_runtime_console'
FROM first_admin_bootstrap_input;
COMMIT;
SQL
  unset email_base64 display_name_base64 token_digest
  echo "first Ops administrator invitation created; deliver the stdin token through an approved channel, then use invitation acceptance to set the password"
}

ensure_migration_ledger() {
  docker compose exec -T postgres psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$database_name" >/dev/null <<'SQL'
    CREATE TABLE IF NOT EXISTS linggan_local_schema_migration (
      migration_id text PRIMARY KEY,
      migration_sha256 text NOT NULL CHECK (migration_sha256 ~ '^[0-9a-f]{64}$'),
      applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
    );
SQL
}

apply_migration_once() {
  local migration_id="$1"
  local migration_path="$2"
  local expected_hash existing_hash
  expected_hash="$(shasum -a 256 "$migration_path" | awk '{print $1}')"
  existing_hash="$(psql_in_container -At -c "SELECT migration_sha256 FROM linggan_local_schema_migration WHERE migration_id = '${migration_id}'")"

  if [[ -n "$existing_hash" ]]; then
    if [[ "$existing_hash" != "$expected_hash" ]]; then
      echo "migration ${migration_id} was previously applied with a different checksum; refusing to continue" >&2
      exit 1
    fi
    echo "migration ${migration_id} already recorded"
    return
  fi

  {
    printf 'BEGIN;\n'
    cat "$migration_path"
    printf "INSERT INTO linggan_local_schema_migration (migration_id, migration_sha256) VALUES ('%s', '%s');\n" "$migration_id" "$expected_hash"
    printf 'COMMIT;\n'
  } | psql_in_container >/dev/null
  echo "migration ${migration_id} applied"
}

